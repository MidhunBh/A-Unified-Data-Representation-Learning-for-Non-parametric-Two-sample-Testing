
import json
import os
import pickle

import numpy as np
import torch
import torchvision.transforms as T

from jax import random
from torch.utils.data import DataLoader
from torchvision import datasets
from tqdm import trange

from mmd_fuse import mmdfuse
from utils import sample_mnist_semi


# ============================================================
# LOCKED CONFIGURATION
# ============================================================

INTERNAL_N = [100, 200, 300, 400, 500]
N_TRIALS = 100

PAPER = {
    200: .320,
    400: .870,
    600: 1.0,
    800: 1.0,
    1000: 1.0,
}

OUT = (
    "result/"
    "mmdfuse_mnist_fullgrid_100trials.json"
)

PKL = (
    "result/"
    "mmdfuse_mnist_fullgrid_100trials.pkl"
)

os.makedirs("result", exist_ok=True)


# ============================================================
# DATA
# ============================================================

np.random.seed(819)
torch.manual_seed(819)

loader = DataLoader(
    datasets.MNIST(
        "./data/mnist",
        train=True,
        download=False,
        transform=T.Compose([
            T.Resize(32),
            T.ToTensor(),
            T.Normalize([.5], [.5]),
        ]),
    ),
    batch_size=60000,
    shuffle=True,
)

real, _ = next(iter(loader))

with open(
    "./data/Fake_MNIST_data_EP100_N10000.pckl",
    "rb",
) as f:
    fake = torch.from_numpy(
        pickle.load(f)[0]
    ).float()


# ============================================================
# CHECKPOINT
# ============================================================

def new_state():
    return {
        "method": "MMD-FUSE",
        "dataset": "MNIST vs Fake MNIST",

        "configuration": {
            "representation": "raw flattened 32x32 pixels",
            "kernels": ["laplace", "gaussian"],
            "bandwidths_per_kernel": 10,
            "permutations": 2000,
            "alpha": .05,
            "trials": N_TRIALS,
            "seed": 42,
        },

        "accounting": {
            "internal_n": INTERNAL_N,
            "paper_M": [2 * n for n in INTERNAL_N],
            "note": (
                "MMD-FUSE has no train/test learning split. "
                "The n train and n test samples generated by "
                "sample_mnist_semi are combined, so each "
                "distribution contains paper_M = 2*n samples."
            ),
        },

        "paper": {
            str(M): value
            for M, value in PAPER.items()
        },

        "points": {},
    }


if os.path.exists(OUT):
    with open(OUT, "r") as f:
        state = json.load(f)

    print("Resuming:", OUT)
else:
    state = new_state()


def save():
    tmp = OUT + ".tmp"

    with open(tmp, "w") as f:
        json.dump(
            state,
            f,
            indent=2,
        )

    os.replace(tmp, OUT)

    with open(PKL, "wb") as f:
        pickle.dump(state, f)


# ============================================================
# FULL PAPER GRID
# ============================================================

for n in INTERNAL_N:
    paper_M = 2 * n
    key = str(n)

    if key not in state["points"]:
        state["points"][key] = {
            "internal_n": n,
            "paper_M": paper_M,
            "outputs": [],
        }

    point = state["points"][key]
    outputs = point["outputs"]
    start = len(outputs)

    if start >= N_TRIALS:
        print(
            f"M={paper_M}: already complete "
            f"({np.mean(outputs):.3f})"
        )
        continue

    bar = trange(
        start,
        N_TRIALS,
        initial=start,
        total=N_TRIALS,
        desc=f"MMD-FUSE M={paper_M}",
    )

    for kk in bar:
        a, b, c, d = sample_mnist_semi(
            real,
            fake,
            n,
            n,
            kk=kk,
        )

        # MMD-FUSE uses all paper_M samples.
        X = torch.cat(
            [a, b],
            dim=0,
        ).numpy()

        Y = torch.cat(
            [c, d],
            dim=0,
        ).numpy()

        X = X.reshape(
            paper_M, -1
        ).astype(np.float32)

        Y = Y.reshape(
            paper_M, -1
        ).astype(np.float32)

        # Deterministic independent key per grid point/trial.
        rng = random.PRNGKey(42)
        rng = random.fold_in(
            rng,
            paper_M,
        )
        rng = random.fold_in(
            rng,
            kk,
        )

        h = int(
            mmdfuse(
                X,
                Y,
                rng,
                alpha=.05,
                kernels=(
                    "laplace",
                    "gaussian",
                ),
                number_bandwidths=10,
                number_permutations=2000,
            )
        )

        outputs.append(h)

        point["power"] = float(
            np.mean(outputs)
        )
        point["completed"] = len(outputs)

        save()

        bar.set_postfix(
            power=f"{point['power']:.3f}"
        )

    print(
        f"\nM={paper_M}: "
        f"power={point['power']:.3f} "
        f"paper={PAPER[paper_M]:.3f}"
    )


# ============================================================
# FINAL SUMMARY
# ============================================================

powers = []

for n in INTERNAL_N:
    point = state["points"][str(n)]

    power = float(
        np.mean(point["outputs"])
    )

    point["power"] = power
    point["completed"] = len(
        point["outputs"]
    )

    powers.append(power)

save()

print("\n==============================")
print("FINAL MMD-FUSE FULL GRID")
print("==============================")

for n, power in zip(
    INTERNAL_N,
    powers,
):
    M = 2 * n

    print(
        f"M={M:4d} "
        f"MMD-FUSE={power:.3f} "
        f"paper={PAPER[M]:.3f}"
    )

print()
print(
    "ours  =",
    [round(x, 3) for x in powers],
)
print(
    "paper =",
    [PAPER[2*n] for n in INTERNAL_N],
)
print("saved =", OUT)
